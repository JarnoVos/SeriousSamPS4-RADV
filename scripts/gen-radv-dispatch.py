#!/usr/bin/env python3
"""Write platform/ps4/radv_vk_dispatch.cpp from Mesa's vk.xml.

RADV's static library exports vk_icdGetInstanceProcAddr only. The Serious Engine
calls the global vk* entry points, so this file is those symbols. Surface,
swapchain, queue submit and instance/device creation are implemented in
videoout_wsi.cpp and are not forwarded.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SKIP = {
    "vkEnumerateInstanceExtensionProperties",
    "vkEnumerateDeviceExtensionProperties",
    "vkCreateInstance",
    "vkCreateDevice",
    "vkDestroySurfaceKHR",
    "vkGetPhysicalDeviceSurfaceSupportKHR",
    "vkGetPhysicalDeviceSurfaceCapabilitiesKHR",
    "vkGetPhysicalDeviceSurfaceFormatsKHR",
    "vkGetPhysicalDeviceSurfacePresentModesKHR",
    "vkCreateSwapchainKHR",
    "vkDestroySwapchainKHR",
    "vkGetSwapchainImagesKHR",
    "vkAcquireNextImageKHR",
    "vkAcquireNextImage2KHR",
    "vkQueuePresentKHR",
    "vkQueueSubmit",
    "vkGetInstanceProcAddr",
    "vkGetDeviceProcAddr",
}


def flat(elem):
    parts = [elem.text or ""]
    for child in list(elem):
        parts.append(flat(child))
        parts.append(child.tail or "")
    return "".join(parts)


def proto_of(proto):
    parts = [proto.text or ""]
    for child in list(proto):
        if child.tag == "name":
            name = child.text
            break
        parts.append(flat(child))
        parts.append(child.tail or "")
    else:
        raise SystemExit("command proto has no name")
    ret = " ".join("".join(parts).split())
    return ret, name


def param_ok(param):
    api = param.get("api")
    if not api:
        return True
    return "vulkan" in api.split(",")


def decl_of(param):
    return " ".join(flat(param).split())


def wants_vulkan(cmd):
    api = cmd.get("api")
    if not api:
        return True
    return "vulkan" in api.split(",")


def main():
    xml_path, header_path, out_path = map(Path, sys.argv[1:4])
    header = header_path.read_text(encoding="utf-8", errors="replace")
    root = ET.parse(xml_path).getroot()
    seen = set()
    functions = []
    for cmd in root.find("commands"):
        if not wants_vulkan(cmd) or cmd.find("proto") is None:
            continue
        ret, name = proto_of(cmd.find("proto"))
        if name in seen or name in SKIP or f"{name}(" not in header:
            continue
        seen.add(name)
        params = [decl_of(p) for p in cmd.findall("param") if param_ok(p)]
        names = [p.find("name").text for p in cmd.findall("param") if param_ok(p)]
        if len(names) != len(set(names)):
            raise SystemExit(f"duplicate parameter in {name}: {names}")
        functions.append((ret, name, params, names))

    lines = [
        "/* Generated by scripts/gen-radv-dispatch.py. Forwards vk* to RADV. */",
        "#include <vulkan/vulkan_core.h>",
        "",
        'extern "C" PFN_vkVoidFunction ss_radv_resolve(const char *name);',
        "",
        'extern "C" {',
        "",
    ]
    for ret, name, params, names in functions:
        args = ", ".join(params) if params else "void"
        call = ", ".join(names)
        lines.append(f"VKAPI_ATTR {ret} VKAPI_CALL {name}({args}) {{")
        lines.append(f"  static PFN_{name} fn;")
        lines.append(f'  if (!fn) fn = (PFN_{name})ss_radv_resolve("{name}");')
        if ret == "void":
            lines.append(f"  fn({call});")
        else:
            lines.append(f"  return fn({call});")
        lines.append("}")
        lines.append("")
    lines.append("}")
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(functions)} entry points -> {out_path}")


if __name__ == "__main__":
    main()
